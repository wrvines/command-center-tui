#!/usr/bin/env python3
"""Render repository theme adapters; never install or activate user configuration."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def render():
    theme = json.loads((ROOT / "config/themes/oh-my-pi.json").read_text())
    roles = theme["roles"]
    if theme["name"] != "oh-my-pi" or len(theme["ansi"]) != 16:
        raise ValueError("Expected oh-my-pi and 16 ANSI role names")
    for value in roles.values():
        if not re.fullmatch(r"#[0-9a-f]{6}", value):
            raise ValueError("Expected lowercase #rrggbb colors")
    ghostty = ["# Generated by scripts/themes.py from config/themes/oh-my-pi.json.",
               "# OhMyPi-DarkTerminal: user palette adapted from Oh My Pi dark-terminal."]
    for option, role in (("background", "background"), ("foreground", "foreground"),
                         ("cursor-color", "primary"), ("cursor-text", "background"),
                         ("selection-background", "border"), ("selection-foreground", "foreground")):
        ghostty.append(f"{option} = {roles[role]}")
    for index, role in enumerate(theme["ansi"]):
        ghostty.append(f"palette = {index}={roles[role]}")

    # Explicit UI components retain subtle inactive borders and green focus.
    # Each tuple is base, background, emphasis_0 .. emphasis_3.
    normal = ("foreground", "background", "primary", "secondary", "cyan", "warning")
    selected = ("foreground", "border", "primary", "secondary", "cyan", "warning")
    components = {
        "text_unselected": normal,
        "text_selected": selected,
        "ribbon_unselected": ("muted", *normal[1:]),
        "ribbon_selected": ("background", "primary", "background", "border", "background", "border"),
        "table_title": ("secondary", *normal[1:]),
        "table_cell_unselected": normal,
        "table_cell_selected": selected,
        "list_unselected": normal,
        "list_selected": selected,
        "frame_unselected": ("border", *normal[1:]),
        "frame_selected": ("primary", *normal[1:]),
        "frame_highlight": ("cyan", *normal[1:]),
        "exit_code_success": ("primary", *normal[1:]),
        "exit_code_error": ("error", *normal[1:]),
    }
    zellij = ["// Generated by scripts/themes.py from config/themes/oh-my-pi.json.",
              "themes {", "    oh-my-pi {"]
    attributes = ("base", "background", "emphasis_0", "emphasis_1", "emphasis_2", "emphasis_3")
    def rgb(role):
        value = roles[role]
        return " ".join(str(int(value[i:i + 2], 16)) for i in (1, 3, 5))
    for component, colors in components.items():
        zellij.append(f"        {component} {{")
        for attribute, role in zip(attributes, colors):
            zellij.append(f"            {attribute} {rgb(role)}")
        zellij.append("        }")
    zellij.append("        multiplayer_user_colors {")
    for index, role in enumerate(("primary", "secondary", "cyan", "warning", "foreground",
                                  "primary", "secondary", "cyan", "warning", "foreground"), 1):
        zellij.append(f"            player_{index} {rgb(role)}")
    zellij.extend(["        }", "    }", "}"])
    return {
        ROOT / "config/ghostty/themes/OhMyPi-DarkTerminal": "\n".join(ghostty) + "\n",
        ROOT / "config/zellij/themes/oh-my-pi.kdl": "\n".join(zellij) + "\n",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail on adapter drift without writing files")
    args = parser.parse_args()
    for target, content in render().items():
        if args.check:
            if not target.is_file() or target.read_text() != content:
                parser.exit(1, f"Theme adapter out of date: {target}; run python3 -B scripts/themes.py\n")
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content)
        print(("Checked: " if args.check else "Rendered: ") + str(target.relative_to(ROOT)))


if __name__ == "__main__":
    main()
